import assert from 'node:assert/strict';
import {availableTimelineModes,currentOperational,normalizeDateRange,packingDuplicate,periodBounds,quickAccessTasks,shiftCursor,uniqueRecordsById} from '../src/operational-data.js';
assert.deepEqual(availableTimelineModes({startDate:'2026-01-01',endDate:'2026-01-05'}),['all','day']);
assert.deepEqual(availableTimelineModes({startDate:'2026-01-01',endDate:'2026-01-12'}),['all','day','week']);
assert(availableTimelineModes({startDate:'2026-01-01',endDate:'2026-02-15'}).includes('month'));
assert.deepEqual(periodBounds('day','2026-01-07'),['2026-01-07','2026-01-07']);
assert.equal(shiftCursor('2026-01-07','day',1),'2026-01-08');
assert.equal(packingDuplicate([{items:[{id:'1',name:'Passport'}]}],' passport '),true);
const items=[{id:'h',type:'hotel',schedule:'range',startAt:'2026-01-06T12:00',endAt:'2026-01-09T12:00'},{id:'f',type:'flight',schedule:'single',startAt:'2026-01-08T12:00'},{id:'i',type:'insurance',schedule:'entire',startAt:''}];
const op=currentOperational(items,'2026-01-07');
assert.equal(op.currentHotel.id,'h');
assert.equal(op.nextTransport.id,'f');
assert.equal(op.activeEntire[0].id,'i');
assert.deepEqual(uniqueRecordsById([undefined,op.nextTransport,null,op.activeEntire[0],op.nextTransport],5).map(item=>item.id),['f','i']);
assert.deepEqual(normalizeDateRange('2026-01-12','2026-01-10'),{start:'2026-01-12',end:'2026-01-12'});
assert.deepEqual(normalizeDateRange('2026-01-12','2026-01-15'),{start:'2026-01-12',end:'2026-01-15'});
const tasks=[{id:'none',dueDate:'',done:false},{id:'future',dueDate:'2026-01-10',done:false},{id:'today',dueDate:'2026-01-07',done:false},{id:'past',dueDate:'2026-01-06',done:false},{id:'done',dueDate:'2026-01-05',done:true}];
assert.deepEqual(quickAccessTasks(tasks,'2026-01-07',3).map(task=>task.id),['past','today','future']);
console.log('V5 operational data tests passed.');
